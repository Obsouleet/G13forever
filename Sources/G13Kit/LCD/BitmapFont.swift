    /// Ersatzzeichen für alles, was die Schrift nicht kennt.
    public static let fallback: [UInt8] = [0x02, 0x01, 0x51, 0x09, 0x06] // "?"

    public static func glyph(for character: Character) -> [UInt8] {
        glyphs[character] ?? fallback
    }

    /// Breite eines einzeiligen Texts in Pixeln (ohne Abstand nach dem letzten Zeichen).
    public static func width(of text: String) -> Int {
        text.isEmpty ? 0 : text.count * advance - 1
