// MARK: - Text zeichnen

extension LCDFrame {

    /// Zeichnet eine Textzeile mit der oberen linken Ecke bei (x, y).
    public mutating func drawText(_ text: String, x: Int, y: Int) {
        var cx = x
        for character in text {
            let glyph = BitmapFont.glyph(for: character)
            for col in 0..<BitmapFont.glyphWidth {
                for row in 0..<BitmapFont.glyphHeight where (glyph[col] >> UInt8(row)) & 1 == 1 {
                    self[cx + col, y + row] = true
                }
            }
            cx += BitmapFont.advance
        }
    }

    /// Bricht Text an Wortgrenzen um, sodass jede Zeile höchstens `maxWidth` Pixel breit ist.
    /// Zu lange Einzelwörter werden hart getrennt.
    public static func wrap(_ text: String, maxWidth: Int = LCDFrame.width) -> [String] {
        let maxChars = max(1, (maxWidth + 1) / BitmapFont.advance)
        var lines: [String] = []
        for paragraph in text.split(separator: "\n", omittingEmptySubsequences: false) {
            var current = ""
            for word in paragraph.split(separator: " ") {
                var word = String(word)
                while word.count > maxChars {
                    if !current.isEmpty { lines.append(current); current = "" }
                    lines.append(String(word.prefix(maxChars)))
                    word = String(word.dropFirst(maxChars))
                }
                let candidate = current.isEmpty ? word : current + " " + word
                if candidate.count > maxChars {
                    lines.append(current)
                    current = word
                } else {
                    current = candidate
                }
            }
            lines.append(current)
        }
        return lines
    }

    /// Erzeugt einen Frame mit umbrochenem, horizontal und vertikal zentriertem Text
    /// (höchstens 5 Zeilen, weitere werden abgeschnitten).
    public static func text(_ text: String) -> LCDFrame {
        var frame = LCDFrame()
        let maxLines = (LCDFrame.height + 1) / BitmapFont.lineHeight // 5
        let lines = Array(wrap(text).prefix(maxLines))
        let blockHeight = lines.count * BitmapFont.lineHeight - 1
        var y = (LCDFrame.height - blockHeight) / 2
        for line in lines {
            let x = (LCDFrame.width - BitmapFont.width(of: line)) / 2
            frame.drawText(line, x: x, y: y)
            y += BitmapFont.lineHeight
        }
        return frame
    }
}
